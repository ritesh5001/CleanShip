const fs = require("fs");
const path = require("path");
const { withDangerousMod } = require("expo/config-plugins");

/**
 * Pins the Gradle wrapper to a version the Android Gradle Plugin supports.
 *
 * React Native 0.86's template ships a wrapper pinned to Gradle 9.3.1, while
 * the AGP it resolves is 8.12.0 — and AGP 8.12 requires Gradle 8.13. That
 * combination is not merely unsupported, it fails: Gradle 9 validates task
 * inputs more strictly than AGP 8.12 was written for, and `mergeExtDexRelease`
 * dies on a `fileDependencyDexDir` that AGP never creates when a build has no
 * file dependencies to desugar.
 *
 *   > A problem was found with the configuration of task ':app:mergeExtDexRelease'
 *   > property 'fileDependencyDexDir' specifies directory '…' which doesn't exist
 *
 * It fails ~7 minutes in, at dex merging, long after everything looks healthy.
 *
 * This is an upstream template mismatch, not a project one, so the fix belongs
 * here rather than in a hand-edit: `android/` is regenerated by every
 * `expo prebuild`, which would silently restore 9.3.1 and the failure with it.
 *
 * REVISIT when React Native ships a template whose AGP and Gradle versions
 * agree. Check with:
 *
 *   cd android && ./gradlew -q buildEnvironment | grep 'com.android.tools.build:gradle'
 *
 * and compare against https://developer.android.com/build/releases/about-agp
 */
const GRADLE_VERSION = "8.13";

module.exports = function withGradleWrapperVersion(config) {
  return withDangerousMod(config, [
    "android",
    (cfg) => {
      const file = path.join(
        cfg.modRequest.platformProjectRoot,
        "gradle",
        "wrapper",
        "gradle-wrapper.properties",
      );

      if (!fs.existsSync(file)) {
        /* Nothing to pin — a prebuild that did not produce a wrapper has
           bigger problems, and failing here would hide them. */
        return cfg;
      }

      const before = fs.readFileSync(file, "utf8");
      const after = before.replace(
        /distributionUrl=.*gradle-[\d.]+(-\w+)?-bin\.zip/,
        `distributionUrl=https\\://services.gradle.org/distributions/gradle-${GRADLE_VERSION}-bin.zip`,
      );

      if (after !== before) {
        fs.writeFileSync(file, after);
        console.log(`✔ Pinned Gradle wrapper to ${GRADLE_VERSION} (AGP compatibility)`);
      }

      return cfg;
    },
  ]);
};
